#!/usr/bin/env python3
"""Generates the synthetic 1.2M-document report corpus used by this project.

Every document is synthetic: no real intelligence, law-enforcement, or
government report content of any kind is used or imitated beyond generic
facet names (category, region, priority, source type, classification).
Output is one JSON object per line (NDJSON) at data/documents.ndjson,
gitignored and regenerated by this script, not committed.
"""
import json
import random
import sys
import time

CATEGORIES = [
    "Infrastructure", "Maritime", "Aviation", "Cyber", "Logistics",
    "Communications", "Border", "Industrial",
]
REGIONS = [f"REGION-{i:02d}" for i in range(1, 13)]
PRIORITIES = ["LOW", "MEDIUM", "HIGH", "CRITICAL"]
SOURCE_TYPES = ["SENSOR", "FIELD", "OPEN_SOURCE", "PARTNER"]
CLASSIFICATIONS = ["UNCLASSIFIED", "CUI", "RESTRICTED"]
# Weighted so RESTRICTED is a believable minority, not a third of the corpus.
CLASSIFICATION_WEIGHTS = [0.55, 0.35, 0.10]
STATUSES = ["NEW", "IN_REVIEW", "FLAGGED", "CLOSED"]
STATUS_WEIGHTS = [0.55, 0.25, 0.12, 0.08]

SUBJECTS = [
    "a convoy", "a vessel", "a facility", "a transformer station", "a relay tower",
    "a checkpoint", "a warehouse", "a pipeline segment", "a rail junction",
    "an airfield", "a cargo terminal", "a substation", "a border crossing",
    "a fiber junction box", "a storage depot",
]
ACTIONS = [
    "reported unusual activity near", "was observed departing", "logged an anomaly at",
    "experienced an outage near", "was flagged for inspection at", "transmitted an alert from",
    "was photographed close to", "filed a routine status update from",
    "triggered a sensor alert near", "was cross-referenced with prior activity at",
]
DETAILS = [
    "Follow-up collection is recommended.", "No further action was taken.",
    "The anomaly was consistent with scheduled maintenance.",
    "A second source could not corroborate the observation.",
    "The report was cross-checked against the prior week's log.",
    "Weather conditions limited the quality of the observation.",
    "The observation matches a known seasonal pattern.",
    "Analysts requested additional imagery of the area.",
    "The source has a moderate reliability rating.",
    "This is the third such report from this area this month.",
]


def make_document(i: int, rng: random.Random) -> dict:
    category = rng.choice(CATEGORIES)
    region = rng.choice(REGIONS)
    subject = rng.choice(SUBJECTS)
    action = rng.choice(ACTIONS)
    title = f"{category} report: {subject} {action} {region}"
    body_sentences = [f"{subject.capitalize()} {action} {region}."]
    body_sentences.append(rng.choice(DETAILS))
    body_sentences.append(rng.choice(DETAILS))
    body = " ".join(body_sentences)
    classification = rng.choices(CLASSIFICATIONS, weights=CLASSIFICATION_WEIGHTS)[0]
    status = rng.choices(STATUSES, weights=STATUS_WEIGHTS)[0]
    day_offset = rng.randint(0, 729)
    created = time.strftime("%Y-%m-%d", time.gmtime(1_700_000_000 - day_offset * 86400))
    return {
        "id": f"doc-{i:08d}",
        "title": title,
        "body": body,
        "category": category,
        "region": region,
        "priority": rng.choice(PRIORITIES),
        "source_type": rng.choice(SOURCE_TYPES),
        "classification": classification,
        "status": status,
        "created_date": created,
    }


def main() -> None:
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 1_200_000
    out_path = sys.argv[2] if len(sys.argv) > 2 else "data/documents.ndjson"
    rng = random.Random(20260926)
    start = time.time()
    with open(out_path, "w", encoding="utf-8") as f:
        for i in range(count):
            doc = make_document(i, rng)
            f.write(json.dumps(doc, separators=(",", ":")))
            f.write("\n")
            if (i + 1) % 100_000 == 0:
                elapsed = time.time() - start
                print(f"[gen] {i + 1}/{count} documents, {elapsed:.1f}s elapsed", file=sys.stderr)
    elapsed = time.time() - start
    print(f"[gen] DONE {count} documents written to {out_path} in {elapsed:.1f}s", file=sys.stderr)


if __name__ == "__main__":
    main()
